const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("typescript");
const source = fs.readFileSync(require.resolve("../lib/asset-code.ts"), "utf8");
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const exportsObject = {};
new Function("exports", output)(exportsObject);
const normalize = exportsObject.normalizeAssetRegister;
const code = "E10638C17AA73E82E0531561F20A6A3F";
assert.equal(normalize(code.toLowerCase()), code);
assert.equal(normalize(` \n${code}\r\n`), code);
assert.equal(normalize("E10638C1-7AA7-3E82-E053-1561F20A6A3F"), code);
assert.equal(normalize(`\u200B${code}\uFEFF`), code);
assert.equal(normalize(`https://example.org/aset/${code.toLowerCase()}`), code);
assert.equal(normalize(`https://example.org/?kode_register=${code}`), code);
assert.equal(normalize("001234"), "001234");
assert.equal(normalize("3050201003"), "3050201003");
assert.equal(normalize("ABC-123"), "ABC-123");
assert.equal(normalize(""), "");
assert.equal(normalize("Software Komputer\nE10638D355513F1EE0531561F20A829B · Anti Virus · 8010101001 · 21"), "E10638D355513F1EE0531561F20A829B");
const ambiguous = `${code} · E10638D355513F1EE0531561F20A829B`;
assert.equal(normalize(ambiguous), ambiguous);
console.log("12 register normalization checks passed");
